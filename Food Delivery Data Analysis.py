import numpy as np
import pandas as pd
import matplotlib.pyplot as plt

df = pd.read_csv("Food Delivery Data Analysis.csv")

print(df.head())
print(df.shape)
print(df.info())
print(df.describe())
print(df.isnull().sum())
print(df.duplicated().sum())

df["Order_Date"] = pd.to_datetime(df["Order_Date"])

delivered_df = df[df["Order_Status"] == "Delivered"].copy()
canceled_df = df[df["Order_Status"] == "Cancelled"].copy()

total_orders = len(df)
delivered_orders = len(delivered_df)
canceled_orders = len(canceled_df)
cancellation_rate = canceled_orders / total_orders * 100

total_revenue = delivered_df["Order_Value"].sum()
average_order_value = delivered_df["Order_Value"].mean()
average_delivery_time = delivered_df["Delivery_Time_Min"].mean()
average_rating = delivered_df["Rating"].mean()

restaurant_revenue = delivered_df.groupby("Restaurant")["Order_Value"].sum().sort_values(ascending=False)
cuisine_orders = delivered_df["Cuisine"].value_counts()
cuisine_revenue = delivered_df.groupby("Cuisine")["Order_Value"].sum().sort_values(ascending=False)
monthly_orders = delivered_df.groupby(delivered_df["Order_Date"].dt.month_name())["Order_ID"].count()
payment_methods = delivered_df["Payment_Method"].value_counts()
city_orders = delivered_df["City"].value_counts()
restaurant_ratings = delivered_df.groupby("Restaurant")["Rating"].mean().sort_values(ascending=False)
monthly_revenue = delivered_df.groupby(delivered_df["Order_Date"].dt.to_period("M"))["Order_Value"].sum()
delivery_by_cuisine = delivered_df.groupby("Cuisine")["Delivery_Time_Min"].mean().sort_values(ascending=False)

print("Total Orders:", total_orders)
print("Delivered Orders:", delivered_orders)
print("Canceled Orders:", canceled_orders)
print("Cancellation Rate:", round(cancellation_rate, 2), "%")
print("Total Revenue:", total_revenue)
print("Average Order Value:", round(average_order_value, 2))
print("Average Delivery Time:", round(average_delivery_time, 2), "minutes")
print("Average Customer Rating:", round(average_rating, 2))
print("Top Restaurant by Revenue:", restaurant_revenue.idxmax())
print("Most Popular Cuisine:", cuisine_orders.idxmax())
print("Most Used Payment Method:", payment_methods.idxmax())
print("Highest Order City:", city_orders.idxmax())
print("Highest Rated Restaurant:", restaurant_ratings.idxmax())

